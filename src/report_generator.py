# ── Colours (R, G, B) ─────────────────────────────────────────────────────────────
C_PRIMARY   = (10,  110, 180)
C_DANGER    = (200,  50,  60)
C_WARNING   = (200, 130,   0)
C_NORMAL    = (30,  150,  70)
