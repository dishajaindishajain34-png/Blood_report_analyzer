import { useQuery } from "@tanstack/react-query";
import { createFileRoute, Link } from "@tanstack/react-router";
import { Activity, CheckCircle2, FileText, Timer, Eye } from "lucide-react";
import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  Line,
  LineChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";

import { MetricCard } from "@/components/common/MetricCard";
import { StatusBadge } from "@/components/common/Badges";
import { Disclaimer, ErrorState, PageHeader } from "@/components/common/States";
import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/skeleton";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { api, queryKeys } from "@/services/api";
import { formatDateTime, formatPercent } from "@/utils/format";

export const Route = createFileRoute("/_app/dashboard")({
  head: () => ({
    meta: [
      { title: "Dashboard — HemaVision AI" },
      {
        name: "description",
        content: "Monitor blood smear analysis throughput and review recent AI results.",
      },
      { property: "og:title", content: "Dashboard — HemaVision AI" },
      {
        property: "og:description",
        content: "Monitor blood smear analysis throughput and review recent AI results.",
      },
    ],
  }),
  component: DashboardPage,
});

const cellColors = ["var(--color-chart-1)", "var(--color-chart-2)", "var(--color-chart-3)"];

function DashboardPage() {
  const stats = useQuery({ queryKey: queryKeys.dashboard, queryFn: api.dashboard });
  const analyses = useQuery({ queryKey: queryKeys.analyses, queryFn: api.listAnalyses });

  return (
    <div className="space-y-6">
      <PageHeader
        title="AI Analysis Dashboard"
        subtitle="Monitor blood smear analysis and review recent results."
        actions={
          <Button asChild>
            <Link to="/analyze">New Analysis</Link>
          </Button>
        }
      />

      {stats.isError ? (
        <ErrorState onRetry={() => stats.refetch()} />
      ) : stats.isLoading || !stats.data ? (
        <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
          {Array.from({ length: 4 }).map((_, i) => (
            <Skeleton key={i} className="h-[124px] rounded-xl" />
          ))}
        </div>
      ) : (
        <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
          <MetricCard
            index={0}
            label="Total Analyses"
            value={stats.data.totalAnalyses}
            icon={Activity}
            hint="All time"
          />
          <MetricCard
            index={1}
            label="Successful Analyses"
            value={stats.data.successfulAnalyses}
            icon={CheckCircle2}
            hint="Completed without errors"
          />
          <MetricCard
            index={2}
            label="Recent Reports"
            value={stats.data.recentReports}
            icon={FileText}
            hint="Generated by backend"
          />
          <MetricCard
            index={3}
            label="Avg. Processing Time"
            value={stats.data.averageProcessingTime}
            decimals={1}
            suffix="s"
            icon={Timer}
            hint="Per image"
          />
        </div>
      )}

      <section className="panel overflow-hidden">
        <div className="flex items-center justify-between gap-3 border-b border-border px-5 py-4">
          <div>
            <h3 className="text-sm font-semibold">Recent Analysis</h3>
            <p className="text-xs text-muted-foreground">Latest smear submissions and outcomes.</p>
          </div>
          <Button asChild variant="ghost" size="sm">
            <Link to="/history">View all</Link>
          </Button>
        </div>
        <div className="overflow-x-auto">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Analysis ID</TableHead>
                <TableHead>Date</TableHead>
                <TableHead>Image</TableHead>
                <TableHead className="text-right">Cells Detected</TableHead>
                <TableHead>AI Result</TableHead>
                <TableHead className="text-right">Confidence</TableHead>
                <TableHead>Status</TableHead>
                <TableHead className="text-right">Actions</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {analyses.isLoading &&
                Array.from({ length: 5 }).map((_, i) => (
                  <TableRow key={i}>
                    {Array.from({ length: 8 }).map((__, j) => (
                      <TableCell key={j}>
                        <Skeleton className="h-4 w-full" />
                      </TableCell>
                    ))}
                  </TableRow>
                ))}
              {(analyses.data ?? []).slice(0, 6).map((row) => (
                <TableRow key={row.id}>
                  <TableCell className="font-medium">{row.id}</TableCell>
                  <TableCell className="whitespace-nowrap text-muted-foreground">
                    {formatDateTime(row.createdAt)}
                  </TableCell>
                  <TableCell>
                    <div className="flex items-center gap-2">
                      <img
                        src={row.imageUrl}
                        alt=""
                        loading="lazy"
                        width={32}
                        height={32}
                        className="size-8 shrink-0 rounded-md object-cover"
                      />
                      <span className="max-w-[150px] truncate text-muted-foreground">
                        {row.imageName}
                      </span>
                    </div>
                  </TableCell>
                  <TableCell className="text-right tabular-nums">{row.cellsDetected}</TableCell>
                  <TableCell className="whitespace-nowrap capitalize">
                    {row.riskLevel} indication
                  </TableCell>
                  <TableCell className="text-right tabular-nums">
                    {formatPercent(row.confidence, 0)}
                  </TableCell>
                  <TableCell>
                    <StatusBadge status={row.status} />
                  </TableCell>
                  <TableCell className="text-right">
                    <Button asChild variant="ghost" size="sm">
                      <Link to="/results/$analysisId" params={{ analysisId: row.id }}>
                        <Eye className="size-4" aria-hidden="true" />
                        View
                      </Link>
                    </Button>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </div>
      </section>

      <div className="grid gap-4 lg:grid-cols-2">
        <section className="panel p-5">
          <h3 className="text-sm font-semibold">Blood Cell Distribution</h3>
          <p className="text-xs text-muted-foreground">Aggregated detections across all analyses.</p>
          {stats.data ? (
            <div className="mt-5 h-64">
              <ResponsiveContainer width="100%" height="100%">
                <BarChart data={stats.data.cellDistribution}>
                  <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="var(--color-border)" />
                  <XAxis dataKey="cellType" tickLine={false} axisLine={false} fontSize={12} />
                  <YAxis tickLine={false} axisLine={false} fontSize={12} width={48} />
                  <Tooltip
                    cursor={{ fill: "var(--color-muted)" }}
                    contentStyle={{
                      borderRadius: 10,
                      border: "1px solid var(--color-border)",
                      fontSize: 12,
                    }}
                  />
                  <Bar dataKey="count" radius={[6, 6, 0, 0]}>
                    {stats.data.cellDistribution.map((entry, i) => (
                      <Cell key={entry.cellType} fill={cellColors[i % cellColors.length]} />
                    ))}
                  </Bar>
                </BarChart>
              </ResponsiveContainer>
            </div>
          ) : (
            <Skeleton className="mt-5 h-64 rounded-lg" />
          )}
        </section>

        <section className="panel p-5">
          <h3 className="text-sm font-semibold">Analysis Activity</h3>
          <p className="text-xs text-muted-foreground">Last 7 days.</p>
          {stats.data ? (
            <div className="mt-5 h-64">
              <ResponsiveContainer width="100%" height="100%">
                <LineChart data={stats.data.activity}>
                  <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="var(--color-border)" />
                  <XAxis dataKey="date" tickLine={false} axisLine={false} fontSize={12} />
                  <YAxis tickLine={false} axisLine={false} fontSize={12} width={32} />
                  <Tooltip
                    contentStyle={{
                      borderRadius: 10,
                      border: "1px solid var(--color-border)",
                      fontSize: 12,
                    }}
                  />
                  <Line
                    type="monotone"
                    dataKey="analyses"
                    stroke="var(--color-secondary)"
                    strokeWidth={2.5}
                    dot={{ r: 3, fill: "var(--color-secondary)" }}
                    activeDot={{ r: 5 }}
                  />
                </LineChart>
              </ResponsiveContainer>
            </div>
          ) : (
            <Skeleton className="mt-5 h-64 rounded-lg" />
          )}
        </section>
      </div>

      <Disclaimer />
    </div>
  );
}
