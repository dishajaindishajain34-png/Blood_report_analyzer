DISCLAIMER = (
    "IMPORTANT DISCLAIMER: This report has been generated by an AI-based "
    "image analysis system and is intended as a preliminary, assistive tool ONLY. "
    "It does NOT constitute a medical diagnosis. All findings must be reviewed, "
    "interpreted, and validated by a certified pathologist or licensed medical "
    "professional before any clinical decision is made. Do not use this report "
    "as a substitute for professional medical advice, diagnosis, or treatment."
)


def _safe(text: str) -> str:
    """Strip or replace any characters outside Latin-1 range."""
    # Replace common unicode symbols with ASCII equivalents
    replacements = {
        "\u2713": "[OK]", "\u2714": "[OK]",
        "\u26a0": "[!]",  "\u26a0\ufe0f": "[!]",
        "\u274c": "[X]",  "\u2716": "[X]",
        "\u2764": "<3",   "\u2665": "<3",
        "\u2605": "*",
        "\u2019": "'",    "\u2018": "'",
        "\u201c": '"',    "\u201d": '"',
        "\u2013": "-",    "\u2014": "--",
        "\u00b5": "u",    # micro sign -> u
        "\u00b1": "+/-",
        "\u00d7": "x",
    }
    for src, dst in replacements.items():
        text = text.replace(src, dst)
    # Drop any remaining non-Latin-1 characters
    return text.encode("latin-1", errors="replace").decode("latin-1")


# ── Charts ────────────────────────────────────────────────────────────────────────
def _make_diff_pie(differential: dict[str, float]) -> bytes:
    labels = list(differential.keys())
    sizes  = [max(v, 0.01) for v in differential.values()]
    colors = ["#3B82F6", "#10B981", "#F59E0B", "#EF4444", "#8B5CF6"]

    fig, ax = plt.subplots(figsize=(4.2, 3.8), facecolor="none")
    wedges, _ = ax.pie(
        sizes, labels=None, colors=colors, startangle=90,
        wedgeprops=dict(width=0.52, edgecolor="white", linewidth=1.5),
    )
    ax.legend(
        wedges,
        [f"{l}  {v:.1f}%" for l, v in zip(labels, differential.values())],
        loc="center left", bbox_to_anchor=(1.0, 0.5),
        fontsize=8, frameon=False,
    )
    ax.set_title("WBC Differential", fontsize=10, fontweight="bold", color="#1a1a2e")
    buf = io.BytesIO()
    fig.savefig(buf, format="png", bbox_inches="tight", dpi=140, transparent=True)
    plt.close(fig)
    buf.seek(0)
    return buf.read()


# ── PDF class ─────────────────────────────────────────────────────────────────────
class BloodReportPDF(FPDF):
    def header(self):
        pass

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(*C_GREY)
        self.cell(
            0, 8,
            f"AI Blood Report Analyzer  |  Page {self.page_no()}  |  Confidential",
            align="C",
        )


# ── Section heading helper ────────────────────────────────────────────────────────
def _section(pdf: "BloodReportPDF", title: str, W: float):
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*C_PRIMARY)
    pdf.cell(W, 6, _safe(title), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_draw_color(*C_PRIMARY)
    pdf.set_line_width(0.4)
    pdf.line(15, pdf.get_y(), 15 + W, pdf.get_y())
    pdf.ln(3)


# ── Main generator ────────────────────────────────────────────────────────────────
def generate_report(
    analysis_id:        str,
    original_image:     Image.Image | None,
    annotated_image:    Image.Image | None,
    raw_counts:         dict[str, int],
    calibrated_counts:  dict[str, int],
    wbc_differential:   dict[str, float],
    flags:              "AnalysisFlags",
    avg_confidence:     float,
    is_estimated_diff:  bool = True,
    anemia_ml_result:   dict | None = None,
    anemia_image_result:  dict | None = None,
    anemia_fusion_result: dict | None = None,
    output_dir:         str | Path = "reports",
    institute_name:     str = "AI Blood Report Analyzer",
    institute_subtitle: str = "Automated Preliminary Diagnostic System",
) -> Path:
    """
    Generate a PDF blood analysis report and return its Path.
    """
    if not _FPDF_AVAILABLE:
        raise ImportError("fpdf2 is not installed. Run: pip install fpdf2")

    ensure_dir(output_dir)
    out_path = Path(output_dir) / f"{analysis_id}.pdf"

    pdf = BloodReportPDF(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    pdf.set_margins(15, 15, 15)
    W = pdf.w - 30   # usable width

    # ── 1. HEADER BAR ─────────────────────────────────────────────────────────
    pdf.set_fill_color(*C_PRIMARY)
    pdf.rect(0, 0, pdf.w, 36, style="F")

    pdf.set_y(8)
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(*C_WHITE)
    pdf.cell(W + 30, 10, _safe(institute_name), align="C",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(200, 230, 255)
    pdf.cell(W + 30, 6, _safe(institute_subtitle), align="C",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_y(42)

    # ── 2. META ROW ───────────────────────────────────────────────────────────
    col_w = W / 3
    meta_items = [
        ("Analysis ID",  analysis_id),
        ("Generated",    current_timestamp()),
        ("Overall",      flags.overall),
    ]
    for label, _ in meta_items:
        pdf.set_font("Helvetica", "B", 7)
        pdf.set_text_color(*C_GREY)
        pdf.cell(col_w, 5, label.upper(), new_x=XPos.RIGHT)
    pdf.ln()
    for _, value in meta_items:
        color = C_NORMAL if value == "Normal" else (C_DANGER if value == "Abnormal" else C_DARK)
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(*color)
        pdf.cell(col_w, 6, _safe(value), new_x=XPos.RIGHT)
    pdf.ln(10)

    # ── 3. IMAGES ─────────────────────────────────────────────────────────────
    _section(pdf, "Blood Smear Analysis", W)

    if original_image is not None and annotated_image is not None:
        img_w = W / 2 - 3
        img_h = min(img_w * (original_image.height / original_image.width), 55)

        with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
            original_image.save(f.name); orig_tmp = f.name
        with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
            annotated_image.save(f.name); ann_tmp = f.name

        x_left  = 15
        x_right = 15 + img_w + 6
        y_img   = pdf.get_y()

        pdf.image(orig_tmp, x=x_left,  y=y_img, w=img_w, h=img_h)
        pdf.image(ann_tmp,  x=x_right, y=y_img, w=img_w, h=img_h)

        pdf.set_y(y_img + img_h + 1)
        pdf.set_font("Helvetica", "I", 7)
        pdf.set_text_color(*C_GREY)
        pdf.set_x(x_left);  pdf.cell(img_w, 4, "Original Image",        align="C", new_x=XPos.RIGHT)
        pdf.set_x(x_right); pdf.cell(img_w, 4, "Detected Cells (YOLOv8)", align="C")
        pdf.ln(8)
        try:
            os.unlink(orig_tmp)
            os.unlink(ann_tmp)
        except:
            pass
    else:
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(*C_GREY)
        pdf.cell(W, 10, "No blood smear image provided. Object detection and cell morphology analysis skipped.",
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(4)


    # ── 4. CELL COUNT TABLE ───────────────────────────────────────────────────
    _section(pdf, "Cell Count Summary", W)

    col_widths = [W * 0.32, W * 0.18, W * 0.22, W * 0.28]
    headers    = ["Cell Type", "Detected (frame)", "Scaled Est.*", "Status"]

    pdf.set_fill_color(*C_PRIMARY)
    pdf.set_text_color(*C_WHITE)
    pdf.set_font("Helvetica", "B", 8)
    for i, h in enumerate(headers):
        pdf.cell(
            col_widths[i], 7, h, border=0, fill=True, align="C",
            new_x=XPos.RIGHT   if i < len(headers)-1 else XPos.LMARGIN,
            new_y=YPos.LAST    if i < len(headers)-1 else YPos.NEXT,
        )

    row_data = [
        ("Red Blood Cells (RBC)",   raw_counts.get("rbc", 0),      calibrated_counts.get("rbc"),      "rbc"),
        ("White Blood Cells (WBC)", raw_counts.get("wbc", 0),      calibrated_counts.get("wbc"),      "wbc"),
        ("Platelets",               raw_counts.get("platelet", 0), calibrated_counts.get("platelet"), "platelet"),
    ]

    from src.normal_ranges import Severity
    flag_map = {f.cell_type: f for f in flags.cell_flags}

    for i, (label, raw, cal, key) in enumerate(row_data):
        flag = flag_map.get(key)
        if flag:
            if flag.severity == Severity.NORMAL:
                status_color, status_text = C_NORMAL, "[OK] Normal"
            elif flag.severity == Severity.UNKNOWN:
                status_color, status_text = C_GREY, "Undetermined"
            else:
                status_color = C_DANGER
                status_text  = f"[!] {flag.severity.value}"
        else:
            status_color, status_text = C_GREY, "N/A"

        fill_c = C_LIGHT if i % 2 == 0 else C_WHITE
        pdf.set_fill_color(*fill_c)
        pdf.set_text_color(*C_DARK)
        pdf.set_font("Helvetica", "", 8)
        pdf.cell(col_widths[0], 7, _safe(label),      border=0, fill=True, align="L", new_x=XPos.RIGHT)
        pdf.cell(col_widths[1], 7, f"{raw:,}",        border=0, fill=True, align="C", new_x=XPos.RIGHT)
        cal_text = f"{cal:,}" if isinstance(cal, int) else "Undetermined"
        pdf.cell(col_widths[2], 7, cal_text,            border=0, fill=True, align="C", new_x=XPos.RIGHT)
        pdf.set_text_color(*status_color)
        pdf.set_font("Helvetica", "B", 8)
        pdf.cell(col_widths[3], 7, _safe(status_text), border=0, fill=True, align="C",
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(2)
    pdf.set_font("Helvetica", "I", 6.5)
    pdf.set_text_color(*C_GREY)
    pdf.cell(W, 5,
             "* Scaled Est. = rough linear approximation from frame count. "
             "NOT a clinical CBC measurement (cells/uL). "
             "A single microscopy field covers only a tiny fraction of total blood volume.",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(3)


    # ── 4B. ANEMIA NOTE ───────────────────────────────────────────────────────
    # Image-derived Hb/HCT estimates have been removed as they are not clinically
    # valid (single frame object count ≠ laboratory CBC measurement).
    # The CBC-based ML Anemia section below provides the valid secondary stream.


    # ── 4C. ANEMIA ML ANALYSIS (SECONDARY STREAM) ───────────────────────────
    if anemia_ml_result and anemia_ml_result.get("status") == "success":
        _section(pdf, "ANEMIA ML ANALYSIS (Secondary Machine-Learning Stream)", W)
        ml_pred  = anemia_ml_result.get("prediction", "Undetermined")
        ml_prob  = anemia_ml_result.get("probability", 0.0)
        ml_model = anemia_ml_result.get("model_name", "Random Forest")
        ml_ver   = anemia_ml_result.get("model_version", "1.0.0")

        is_ml_anemic = anemia_ml_result.get("is_anemic", False)
        ml_color = C_DANGER if is_ml_anemic else C_NORMAL
        ml_bg    = C_RED_BG if is_ml_anemic else C_GREEN_BG

        pdf.set_fill_color(*ml_bg)
        pdf.set_text_color(*ml_color)
        pdf.set_font("Helvetica", "B", 9)
        pdf.cell(W, 7, f"  ML Prediction: {ml_pred.upper()}  |  Probability: {ml_prob:.1%}  |  Model: {ml_model} (v{ml_ver})",
                 border=0, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_font("Helvetica", "I", 7.5)
        pdf.set_text_color(*C_GREY)
        pdf.cell(W, 5, "  Input CBC: User-entered laboratory parameters. This ML stream operates independently from image detection.",
                 border=0, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(4)

    # ── 4D. ANEMIA IMAGE ANALYSIS ─────────────────────────────────────────────
    if anemia_image_result and anemia_image_result.get("status") == "success":
        _section(pdf, "ANEMIA IMAGE-BASED ANALYSIS (AneRBC Screening Model)", W)
        img_pred = anemia_image_result.get("prediction", "Undetermined")
        img_prob = anemia_image_result.get("probability", 0.0)
        img_model = anemia_image_result.get("model_name", "MobileNetV3")
        img_ver = anemia_image_result.get("model_version", "1.0.0")

        is_img_anemic = anemia_image_result.get("is_anemic", False)
        img_color = C_DANGER if is_img_anemic else C_NORMAL
        img_bg = C_RED_BG if is_img_anemic else C_GREEN_BG

        pdf.set_fill_color(*img_bg)
        pdf.set_text_color(*img_color)
        pdf.set_font("Helvetica", "B", 9)
        pdf.cell(W, 7, f"  Image Prediction: {img_pred.upper()}  |  Probability: {img_prob:.1%}  |  Model: {img_model} (v{img_ver})",
                 border=0, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_font("Helvetica", "I", 7.5)
        pdf.set_text_color(*C_GREY)
        pdf.cell(W, 5, "  Input: Microscope blood smear image features. This model operates independently from CBC inputs.",
                 border=0, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(4)

    # ── 4E. FINAL FUSED ANEMIA ASSESSMENT ─────────────────────────────────────
    if anemia_fusion_result and anemia_fusion_result.get("status") == "success":
        _section(pdf, "FINAL FUSED ANEMIA ASSESSMENT (Multimodal AI Fusion)", W)
        fuse_pred = anemia_fusion_result.get("fusion_prediction", "Undetermined")
        fuse_prob = anemia_fusion_result.get("fusion_probability", 0.0)
        fuse_strategy = anemia_fusion_result.get("fusion_strategy", "average_fallback")
        fuse_ver = anemia_fusion_result.get("model_version", "1.0.0")

        is_fuse_anemic = anemia_fusion_result.get("is_anemic", False)
        fuse_color = C_DANGER if is_fuse_anemic else C_NORMAL
        fuse_bg = C_RED_BG if is_fuse_anemic else C_GREEN_BG

        pdf.set_fill_color(*fuse_bg)
        pdf.set_text_color(*fuse_color)
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(W, 8, f"  FINAL ASSESSMENT: {fuse_pred.upper()}  |  Fused Probability: {fuse_prob:.1%}",
                 border=0, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_font("Helvetica", "I", 8)
        pdf.set_text_color(*C_GREY)
        strategy_desc = {
            "learned_stacking_ensemble": "Learned Multimodal Fusion (Stacking Ensemble Model)",
            "learned_logistic_regression": "Learned Multimodal Fusion (Logistic Regression Model)",
            "learned_lr": "Learned Multimodal Fusion (Logistic Regression Model)",
            "average_fallback": "Fallback Fusion - trained fusion model unavailable",
            "image_only": "Image Modality Only",
            "cbc_only": "CBC Modality Only",
            "experimental_gmu_dual": "Experimental GMU Fusion (Dual-Modality: Smear + CBC)",
            "experimental_gmu_image_only": "Experimental GMU Fusion (Image Modality Only)",
            "experimental_gmu_cbc_only": "Experimental GMU Fusion (CBC Modality Only)",
        }.get(fuse_strategy, fuse_strategy)
        gate_info = ""
        gate_val = anemia_fusion_result.get("latent_gate_mean")
        if gate_val is not None:
            try:
                gate_info = f"  |  GMU Gate Mean: {float(gate_val):.3f}"
            except Exception:
                pass
        pdf.cell(W, 5, f"  Fusion Strategy: {strategy_desc}  |  Version: {fuse_ver}{gate_info}",
                 border=0, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        if anemia_fusion_result.get("is_experimental") or "experimental" in str(fuse_strategy).lower():
            pdf.set_font("Helvetica", "B", 7.5)
            pdf.set_text_color(*C_WARNING)
            pdf.cell(W, 5, "  [!] NOTICE: Experimental GMU Model trained on synthetic pairings. Academic prototype only.",
                     border=0, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(4)

    # ── 5. WBC DIFFERENTIAL ───────────────────────────────────────────────────
    est_suffix = " (Estimated *)" if is_estimated_diff else ""
    _section(pdf, f"WBC Differential Count{est_suffix}", W)

    # Embed pie chart on the right side
    # Save current Y position before placing pie/table so we can avoid overlaps
    y_start = pdf.get_y()
    pie_bytes = _make_diff_pie(wbc_differential)
    with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
        f.write(pie_bytes); pie_tmp = f.name

    pie_w, pie_h = 66, 52
    pdf.image(pie_tmp, x=15 + W - pie_w, y=pdf.get_y(), w=pie_w, h=pie_h)
    os.unlink(pie_tmp)

    # Table left of pie
    diff_col_w = [W * 0.30, W * 0.20, W * 0.18, W * 0.32]
    pdf.set_font("Helvetica", "B", 7)
    pdf.set_text_color(*C_GREY)
    for txt, cw in zip(["Subtype", "Percent", "Ref. Range", "Status"], diff_col_w):
        pdf.cell(cw, 5, txt.upper(), new_x=XPos.RIGHT)
    pdf.ln()

    diff_flag_map = {f.cell_type: f for f in flags.diff_flags}
    for j, (subtype, pct) in enumerate(wbc_differential.items()):
        flag = diff_flag_map.get(subtype)
        if flag:
            s_color = C_NORMAL if flag.severity == Severity.NORMAL else C_WARNING
            s_text  = "[OK] Normal" if flag.severity == Severity.NORMAL else f"[!] {flag.severity.value}"
        else:
            s_color, s_text = C_GREY, "N/A"

        fill_c = C_LIGHT if j % 2 == 0 else C_WHITE
        pdf.set_fill_color(*fill_c)
        pdf.set_text_color(*C_DARK)
        pdf.set_font("Helvetica", "", 7)
        pdf.cell(diff_col_w[0], 6, _safe(subtype), fill=True, new_x=XPos.RIGHT)
        pdf.cell(diff_col_w[1], 6, f"{pct:.1f}%",  fill=True, align="C", new_x=XPos.RIGHT)

        from src.normal_ranges import WBC_DIFF_RANGES
        ref = WBC_DIFF_RANGES.get(subtype, {})
        ref_txt = f"{ref.get('min','')}--{ref.get('max','')}%"
        pdf.cell(diff_col_w[2], 6, ref_txt, fill=True, align="C", new_x=XPos.RIGHT)
        pdf.set_text_color(*s_color)
        pdf.set_font("Helvetica", "B", 7)
        pdf.cell(diff_col_w[3], 6, _safe(s_text), fill=True, align="C",
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    if is_estimated_diff:
        pdf.set_font("Helvetica", "I", 6.5)
        pdf.set_text_color(*C_GREY)
        pdf.cell(W, 5,
                 "* Estimated from typical healthy-blood ratios. "
                 "ResNet50 WBC classifier replaces this in Phase 2.",
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    # Ensure we drop below the pie chart before continuing
    # Ensure we drop below the pie chart before continuing. Use saved y_start
    pdf.set_y(max(pdf.get_y(), y_start + pie_h) + 4)

    # ── 6. CLINICAL FLAGS ─────────────────────────────────────────────────────
    _section(pdf, "Clinical Findings & WHO Range Analysis", W)

    for line in flags.summary:
        # Strip unicode emoji characters before checking
        clean_line = _safe(line)
        is_abnormal = "[!]" in clean_line or "Abnormal" in clean_line or "Possible" in clean_line

        if is_abnormal:
            pdf.set_fill_color(*C_AMBER_BG)
            pdf.set_text_color(*C_WARNING)
        else:
            pdf.set_fill_color(*C_GREEN_BG)
            pdf.set_text_color(*C_NORMAL)

        pdf.set_font("Helvetica", "B" if is_abnormal else "", 8)
        pdf.multi_cell(W, 7, clean_line, border=0, fill=True,
                       new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(1)

    # WBC diff abnormal flags
    diff_abnormal = [f for f in flags.diff_flags if f.severity.value != "Normal"]
    if diff_abnormal:
        for f in diff_abnormal:
            line = f"[!] {f.label}: {f.value}% (Ref: {f.reference}) -- {f.condition}"
            pdf.set_fill_color(*C_AMBER_BG)
            pdf.set_text_color(*C_WARNING)
            pdf.set_font("Helvetica", "B", 8)
            pdf.multi_cell(W, 7, _safe(line), border=0, fill=True,
                           new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            pdf.ln(1)

    pdf.ln(4)

    # ── 7. CONFIDENCE SUMMARY ─────────────────────────────────────────────────
    _section(pdf, "AI Detection Confidence", W)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(*C_DARK)
    pdf.cell(
        W, 6,
        f"Average confidence (YOLOv8): {avg_confidence:.1%}    "
        f"Total cells detected in frame: {sum(raw_counts.values())}",
        new_x=XPos.LMARGIN, new_y=YPos.NEXT,
    )
    pdf.ln(4)

    # ── 8. DISCLAIMER ─────────────────────────────────────────────────────────
    pdf.set_fill_color(*C_DANGER)
    pdf.set_text_color(*C_WHITE)
    pdf.set_font("Helvetica", "B", 8)
    pdf.cell(W, 7, "  [!]  MEDICAL DISCLAIMER", fill=True,
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_fill_color(*C_RED_BG)
    pdf.set_text_color(140, 0, 0)
    pdf.set_font("Helvetica", "", 7.5)
    pdf.multi_cell(W, 5, _safe(DISCLAIMER), border=0, fill=True,
                   new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.output(str(out_path))
